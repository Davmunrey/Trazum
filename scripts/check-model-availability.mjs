#!/usr/bin/env node
/**
 * Asks each provider whether the models this repository prices still exist.
 *
 * ## Why this exists
 *
 * The catalogue in `packages/core/src/pricing.ts` is the root of every dollar
 * figure Trazum prints, and `pricing-review.test.js` holds it to a review date
 * so a stale *price* fails a test. Nothing held the *model id*. A price that is
 * still correct for a model the API no longer accepts is not a stale number —
 * it is an answer to a question nobody can ask, and it reads exactly like a
 * good one.
 *
 * The first run of this script, with real credentials, found four:
 *
 * - `gemini-2.5-pro` and `gemini-2.5-flash` — **404**, *"no longer available to
 *   new users"*. Both are still returned by `GET /v1beta/models`, which is why
 *   listing is not the check: listed and callable are different states, and
 *   only a request tells them apart.
 * - `deepseek-v3` — **400**, *"The supported API model names are
 *   deepseek-v4-pro, deepseek-v4-flash…"*.
 * - `mistral-large-2` — **400**, *"Invalid model"*.
 *
 * ## What it does not do
 *
 * It does not repair the catalogue, and it must not be extended to. Finding
 * that a model is gone says nothing about what its replacement costs, and a
 * price this repository did not read off the provider's own page is the one
 * thing it never writes down. The output is a list of questions for a human
 * with a browser, not a patch.
 *
 * It also cannot report on a provider whose key is absent, and says so by name
 * rather than leaving the row out — a report that silently covers three
 * providers of seven and looks like a clean bill is the failure this whole
 * repository is about.
 *
 * ## Running it
 *
 *     ANTHROPIC_API_KEY=… OPENAI_API_KEY=… node scripts/check-model-availability.mjs
 *
 * Every key is optional and every provider is independent. On Anthropic the
 * probe is the free counting endpoint, so that provider costs nothing;
 * elsewhere it is one completion held to the smallest generated half the
 * provider accepts — a fraction of a cent per model, and said out loud because
 * the Anthropic path is free and nobody should learn the difference from an
 * invoice.
 *
 * Exits 1 when any priced model is refused, so a maintainer can run it before
 * a release and a shell can tell.
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { MODELS } from '../packages/core/dist/index.js';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const RECORD = join(repoRoot, 'packages/core/test/fixtures/model-availability.json');

/**
 * The date to stamp the record with, from the caller rather than the clock.
 *
 * `TRAZUM_CHECKED_ON` exists so the record can be reproduced: a fixture whose
 * only moving part is `new Date()` cannot be regenerated by anybody checking
 * this run, and a provenance field nobody can reproduce is decoration.
 */
const CHECKED_ON = process.env.TRAZUM_CHECKED_ON ?? new Date().toISOString().slice(0, 10);

/**
 * One probe per provider, each the cheapest request that provider answers.
 *
 * Deliberately the same shapes `measure-token-band.mjs` uses, for a reason
 * that cost this repository a release: the OpenAI shape committed there was
 * written without a key, and the first real credential answered 400 because
 * `gpt-5` spends a one-token budget on reasoning before it emits. Two scripts
 * guessing separately would have found that twice.
 */
const PROBES = {
  anthropic: {
    envVar: 'ANTHROPIC_API_KEY',
    free: true,
    async ask(id, key) {
      const response = await fetch('https://api.anthropic.com/v1/messages/count_tokens', {
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'anthropic-version': '2023-06-01',
          'x-api-key': key,
        },
        body: JSON.stringify({ model: id, messages: [{ role: 'user', content: 'hi' }] }),
      });
      return [response.status, (await response.json())?.error?.message ?? ''];
    },
  },
  openai: {
    envVar: 'OPENAI_API_KEY',
    free: false,
    async ask(id, key) {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: id,
          messages: [{ role: 'user', content: 'hi' }],
          max_completion_tokens: 16,
        }),
      });
      return [response.status, (await response.json())?.error?.message ?? ''];
    },
  },
  google: {
    envVar: 'GOOGLE_API_KEY',
    free: false,
    async ask(id, key) {
      // The key travels in a header. Google's own examples put it in `?key=`,
      // which writes a credential into every proxy log between here and there.
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${id}:generateContent`,
        {
          method: 'POST',
          headers: { 'content-type': 'application/json', 'x-goog-api-key': key },
          body: JSON.stringify({
            contents: [{ role: 'user', parts: [{ text: 'hi' }] }],
            generationConfig: { maxOutputTokens: 1 },
          }),
        },
      );
      return [response.status, (await response.json())?.error?.message ?? ''];
    },
  },
  deepseek: {
    envVar: 'DEEPSEEK_API_KEY',
    free: false,
    async ask(id, key) {
      const response = await fetch('https://api.deepseek.com/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: id,
          messages: [{ role: 'user', content: 'hi' }],
          max_tokens: 1,
        }),
      });
      return [response.status, (await response.json())?.error?.message ?? ''];
    },
  },
  /**
   * Both of these are OpenAI-shaped, and both were missing.
   *
   * The catalogue prices `grok-4` and `kimi-k2`, and on 2026-08-31 neither is
   * on its provider's published pricing page any more — xAI lists grok-4.3,
   * 4.5, 4.6, 4.20 and grok-build; Moonshot lists kimi-k3, k2.7-code, k2.6,
   * k2.5 and the V1 series. That is a strong hint and it is **not** the check.
   * `retired` records a provider refusing a real request, quoting its own
   * sentence, and a page that stopped mentioning a model has refused nothing.
   * These two probes are what turns the hint into an answer.
   *
   * Written before either key existed, which is deliberate: the alternative is
   * discovering the shape of the request on the day somebody is waiting, and
   * this file's whole argument is that a question worth asking is worth having
   * ready.
   */
  xai: {
    envVar: 'XAI_API_KEY',
    free: false,
    async ask(id, key) {
      const response = await fetch('https://api.x.ai/v1/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: id,
          messages: [{ role: 'user', content: 'hi' }],
          max_tokens: 1,
        }),
      });
      const body = await response.json();
      /* xAI answers `{ code, error }` rather than `{ error: { message } }`. */
      return [response.status, body?.error?.message ?? body?.error ?? ''];
    },
  },
  moonshot: {
    envVar: 'MOONSHOT_API_KEY',
    free: false,
    async ask(id, key) {
      const response = await fetch('https://api.moonshot.ai/v1/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: id,
          messages: [{ role: 'user', content: 'hi' }],
          max_tokens: 1,
        }),
      });
      const body = await response.json();
      return [response.status, body?.error?.message ?? body?.message ?? ''];
    },
  },
  mistral: {
    envVar: 'MISTRAL_API_KEY',
    free: false,
    async ask(id, key) {
      const response = await fetch('https://api.mistral.ai/v1/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: id,
          messages: [{ role: 'user', content: 'hi' }],
          max_tokens: 1,
        }),
      });
      const body = await response.json();
      return [response.status, body?.message ?? body?.error?.message ?? ''];
    },
  },
};

/**
 * A model this catalogue knows it cannot reach with an ordinary key.
 *
 * One entry, and it is not a convenience: `claude-mythos-5` is priced with
 * `recommendable: false` and a note saying it is Project Glasswing only, so a
 * 404 from a key without that access is the documented behaviour rather than a
 * retirement. Listed here by id with its reason, because a probe that quietly
 * forgives a 404 forgives every 404.
 */
const EXPECTED_UNREACHABLE = new Map([
  ['claude-mythos-5', 'priced as Glasswing-only and not recommendable'],
]);

const pad = (text, width) => String(text).padEnd(width);
const providers = [...new Set(MODELS.map((model) => model.provider))].sort();

const skipped = [];
const gone = [];
const reachable = [];

const billed = providers.filter(
  (name) => PROBES[name] !== undefined && !PROBES[name].free && process.env[PROBES[name].envVar],
);
if (billed.length > 0) {
  console.log(
    `\nEvery probe on ${billed.join(', ')} is a real completion held to the smallest\n` +
      'generated half that provider accepts, so the prompt half is billed. A fraction\n' +
      'of a cent per model, and still your money — said out loud because the Anthropic\n' +
      'path is free and nobody should discover the difference on an invoice.\n',
  );
}

/**
 * Did the provider refuse the **credential** rather than the model?
 *
 * This exists because it nearly shipped the exact defect the whole script is
 * against. xAI answers `400 "Incorrect API key provided"` to a bad key — not
 * 401 — and the first version of the `xai` probe duly recorded `grok-4` as
 * GONE, with the provider "quoting" a sentence about the key. A typo in an
 * environment variable would have retired a live model, in the provider's own
 * words, on the record.
 *
 * So the status alone cannot decide it. What decides it is **what the provider
 * said**: an answer naming the key is about the key, whatever number it
 * arrives with. A run that cannot authenticate has not asked the question, and
 * `notAsked` is where an unasked question belongs — the same rule the rate
 * limit already followed, which is why this reads like it.
 *
 * Deliberately broad. A false "could not ask" costs a re-run once somebody
 * fixes the key; a false "GONE" costs a retired model that still works, and
 * this file exists to say those are not the same mistake.
 */
const ABOUT_THE_CREDENTIAL =
  /\b(api[ _-]?key|unauthori[sz]ed|authenticat|credential|invalid[ _-]?token|permission denied|forbidden)\b/i;

const refusedTheCredential = (status, message) =>
  status === 401 || status === 403 || ABOUT_THE_CREDENTIAL.test(String(message));

for (const model of MODELS) {
  const probe = PROBES[model.provider];
  if (probe === undefined) {
    skipped.push([model.id, `no probe is written for ${model.provider}`]);
    continue;
  }
  const key = process.env[probe.envVar];
  if (!key) {
    skipped.push([model.id, `${probe.envVar} is not set`]);
    continue;
  }
  try {
    const [status, message] = await probe.ask(model.id, key);
    if (status === 200) {
      reachable.push(model.id);
      console.log(`  ok       ${pad(model.id, 26)} ${model.provider}`);
    } else if (refusedTheCredential(status, message)) {
      skipped.push([
        model.id,
        `${status} — the provider refused the credential, not the model: `
          + `${String(message).replace(/\s+/g, ' ').trim()}`,
      ]);
      console.log(`  no key   ${pad(model.id, 26)} ${status} — credential refused`);
    } else if (status === 429) {
      // Rate limiting says nothing about whether the model exists, and calling
      // it "gone" would be the flattering direction in reverse: a scary answer
      // manufactured out of a busy minute.
      skipped.push([model.id, `${status} — rate limited, so this says nothing either way`]);
    } else if (EXPECTED_UNREACHABLE.has(model.id)) {
      console.log(
        `  expected ${pad(model.id, 26)} ${status} — ${EXPECTED_UNREACHABLE.get(model.id)}`,
      );
    } else {
      // The whole message, not a preview of it: the useful half is usually at
      // the end, where the provider names the replacement.
      gone.push([model.id, status, String(message).replace(/\s+/g, ' ').trim()]);
      console.log(`  GONE     ${pad(model.id, 26)} ${status}`);
    }
  } catch (error) {
    skipped.push([model.id, `the request failed: ${error.message.slice(0, 80)}`]);
  }
}

/**
 * The record, written whatever the outcome.
 *
 * A refusal that lives only in a terminal is a refusal nobody can hold the
 * catalogue to next week. What is written is what was asked and what came
 * back, per model — including the ones that could not be asked, which is the
 * half a report likes to drop.
 */
await writeFile(
  RECORD,
  `${JSON.stringify(
    {
      checkedOn: CHECKED_ON,
      note:
        'Written by scripts/check-model-availability.mjs. Refused means the provider '
        + 'answered a real request for this id with an error, not that a list omitted it.',
      answered: reachable,
      expectedUnreachable: MODELS.filter((model) => EXPECTED_UNREACHABLE.has(model.id)).map(
        (model) => ({ id: model.id, because: EXPECTED_UNREACHABLE.get(model.id) }),
      ),
      refused: gone.map(([id, status, message]) => ({ id, status, message })),
      notAsked: skipped.map(([id, because]) => ({ id, because })),
    },
    null,
    2,
  )}\n`,
);

console.log(`\n${reachable.length} of ${MODELS.length} priced models answered.`);
console.log('Written to packages/core/test/fixtures/model-availability.json');

if (skipped.length > 0) {
  console.log(`\n${skipped.length} could not be asked, and that is not a pass:`);
  for (const [id, reason] of skipped) console.log(`  ${pad(id, 26)} ${reason}`);
}

if (gone.length === 0) {
  console.log('\nNothing priced here was refused by the provider that sells it.');
  process.exit(0);
}

console.log(`\n${gone.length} priced ${gone.length === 1 ? 'model is' : 'models are'} refused:\n`);
for (const [id, status, message] of gone) {
  console.log(`  ${id} — ${status}`);
  console.log(`    ${message.slice(0, 160)}\n`);
}
console.log(
  'What to do with this list: read the replacement price off the provider\'s own\n' +
    'pricing page, on a date, and update pricing.ts and PROVIDER_REVIEWED together.\n' +
    'Nothing here proposes a number, and a number from anywhere but that page is\n' +
    'the one mistake this product does not get to make.',
);
process.exit(1);
